import { config } from '../config.js';
import { sql } from '../db/index.js';

/** Проверенные инструкции для AI (подмешиваются в БЛОК ДАННЫХ при SUPPORT_AI_KNOWLEDGE_ENABLED). Только общие шаги, без секретов. */
const KNOWLEDGE = `База знаний:
— Если VPN «то работает, то нет»: 1) обновите подписку в приложении; 2) смените локацию; 3) переключите Wi-Fi/мобильную сеть; 4) перезапустите приложение. Уточните: ОС, приложение, оператор, время сбоя.
— iPhone + мобильный оператор: сбои бывают из-за фильтрации у оператора; полностью исключить их нельзя. Попросите проверить другую локацию и другой протокол/приложение, при повторе — передайте оператору поддержки.
— Подписка не обновляется в приложении: проверьте, что ссылка подписки вставлена полностью (не показывайте её в чате), включён интернет без VPN, попробуйте мобильную сеть/Wi-Fi.
— Оплата прошла, доступа нет: не обещайте срок и возврат, передайте оператору.
— Не просите пароли, коды, ссылки подписки и ключи.`;

export async function knowledgeBlock(): Promise<string> {
  if (!config().SUPPORT_AI_KNOWLEDGE_ENABLED) return '';
  const inc = await sql()`select target, operator from network_incidents where state = 'confirmed' order by started_at desc limit 5`.catch(() => []);
  const status = inc.length
    ? `Сейчас подтверждены проблемы с доступом: ${inc.map((i) => `${i.target} (${i.operator})`).join('; ')}. Скажите, что команда в курсе, и не обещайте сроки.`
    : 'Подтверждённых проблем по данным мониторинга сейчас нет (это не гарантия работы у конкретного оператора). Не утверждай, что «всё работает».';
  return `${KNOWLEDGE}\nСостояние сети: ${status}`;
}
